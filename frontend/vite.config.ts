import react from '@vitejs/plugin-react'
import { defineConfig } from 'vite'
import { VitePWA } from 'vite-plugin-pwa'

// Where the dev proxy sends /api. Override to run against a backend on another port:
//   API_TARGET=http://localhost:8081 npm run dev
const apiTarget = process.env.API_TARGET ?? 'http://localhost:8080'

// https://vite.dev/config/
export default defineConfig({
  plugins: [
    react(),
    // Installable PWA: manifest + service worker. Offline is not a goal for the MVP;
    // the service worker precaches the app shell, the API is always fetched live.
    // Emits sw.js, registerSW.js and manifest.webmanifest (no-cache rules in nginx.conf).
    VitePWA({
      registerType: 'autoUpdate',
      injectRegister: 'auto',
      includeAssets: ['favicon.ico', 'favicon.svg', 'apple-touch-icon-180x180.png'],
      manifest: {
        name: 'Onhand',
        short_name: 'Onhand',
        description: 'What you have at home, and where it is.',
        lang: 'en',
        start_url: '/',
        scope: '/',
        display: 'standalone',
        orientation: 'portrait',
        theme_color: '#F5F6F4',
        background_color: '#F5F6F4',
        // generated by `npm run generate-pwa-assets` from public/icon.svg
        icons: [
          { src: 'pwa-64x64.png', sizes: '64x64', type: 'image/png' },
          { src: 'pwa-192x192.png', sizes: '192x192', type: 'image/png' },
          { src: 'pwa-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
          { src: 'maskable-icon-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
        ],
      },
      workbox: {
        // client-side routes fall back to index.html, but never API calls
        navigateFallbackDenylist: [/^\/api\//],
      },
    }),
  ],
  server: {
    // Same-origin in dev: the browser calls /api, Vite forwards to Spring Boot.
    proxy: {
      '/api': apiTarget,
    },
  },
})
