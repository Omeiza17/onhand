package dev.codingstoic.onhand.location;

import dev.codingstoic.onhand.ApiTestSupport;
import org.junit.jupiter.api.Test;
import org.springframework.http.MediaType;

import static org.assertj.core.api.Assertions.assertThat;

class LocationApiTests extends ApiTestSupport {

	@Test
	void createReturns201WithUuidv7IdAndLocationHeader() {
		post("/api/v1/locations", "{\"name\":\"  Pantry \"}")
				.expectStatus().isCreated()
				.expectHeader().value("Location", h -> assertThat(h).startsWith("/api/v1/locations/"))
				.expectBody()
				.jsonPath("$.name").isEqualTo("Pantry")
				.jsonPath("$.sortOrder").isEqualTo(0)
				// UUID version nibble: 7 = time-ordered, generated by Postgres uuidv7()
				.jsonPath("$.id").value(String.class, id -> assertThat(id.charAt(14)).isEqualTo('7'));
	}

	@Test
	void newLocationsGoToTheEndAndListIsOrdered() {
		createLocation("Pantry");
		createLocation("Fridge");
		post("/api/v1/locations", "{\"name\":\"Spice rack\",\"sortOrder\":0}").expectStatus().isCreated();

		client.get().uri("/api/v1/locations").exchange()
				.expectStatus().isOk()
				.expectBody()
				.jsonPath("$.length()").isEqualTo(3)
				// Pantry=0, Fridge=1, Spice rack=0 → ties broken by name
				.jsonPath("$[0].name").isEqualTo("Pantry")
				.jsonPath("$[1].name").isEqualTo("Spice rack")
				.jsonPath("$[2].name").isEqualTo("Fridge")
				.jsonPath("$[2].sortOrder").isEqualTo(1);
	}

	@Test
	void updateRenamesAndReorders() {
		String id = createLocation("Fridge");

		put("/api/v1/locations/" + id, "{\"name\":\"Big fridge\",\"sortOrder\":5}")
				.expectStatus().isOk()
				.expectBody()
				.jsonPath("$.name").isEqualTo("Big fridge")
				.jsonPath("$.sortOrder").isEqualTo(5);

		// sortOrder omitted → kept
		put("/api/v1/locations/" + id, "{\"name\":\"Fridge\"}")
				.expectStatus().isOk()
				.expectBody().jsonPath("$.sortOrder").isEqualTo(5);
	}

	@Test
	void deleteReturns204ThenLocationIsGone() {
		String id = createLocation("Freezer");

		client.delete().uri("/api/v1/locations/" + id).exchange().expectStatus().isNoContent();
		client.get().uri("/api/v1/locations").exchange()
				.expectBody().jsonPath("$.length()").isEqualTo(0);
	}

	@Test
	void deletingALocationClearsItAsProductDefault() {
		String id = createLocation("Freezer");
		post("/api/v1/products", "{\"name\":\"Peas\",\"trackingMode\":\"COUNTED\",\"defaultLocationId\":\"" + id + "\"}")
				.expectStatus().isCreated();

		client.delete().uri("/api/v1/locations/" + id).exchange().expectStatus().isNoContent();

		client.get().uri("/api/v1/products").exchange()
				.expectBody()
				.jsonPath("$[0].name").isEqualTo("Peas")
				.jsonPath("$[0].defaultLocationId").doesNotExist();
	}

	@Test
	void blankOrTooLongNameIs400WithFieldErrors() {
		post("/api/v1/locations", "{\"name\":\"   \"}")
				.expectStatus().isBadRequest()
				.expectHeader().contentTypeCompatibleWith(MediaType.APPLICATION_PROBLEM_JSON)
				.expectBody()
				.jsonPath("$.status").isEqualTo(400)
				.jsonPath("$.errors[0].field").isEqualTo("name");

		post("/api/v1/locations", "{\"name\":\"" + "x".repeat(61) + "\"}")
				.expectStatus().isBadRequest()
				.expectBody().jsonPath("$.errors[0].field").isEqualTo("name");
	}

	@Test
	void negativeSortOrderIs400() {
		post("/api/v1/locations", "{\"name\":\"Pantry\",\"sortOrder\":-1}")
				.expectStatus().isBadRequest()
				.expectBody().jsonPath("$.errors[0].field").isEqualTo("sortOrder");
	}

	@Test
	void duplicateNameIgnoringCaseIs409() {
		createLocation("Pantry");

		post("/api/v1/locations", "{\"name\":\"PANTRY\"}")
				.expectStatus().isEqualTo(409)
				.expectHeader().contentTypeCompatibleWith(MediaType.APPLICATION_PROBLEM_JSON)
				.expectBody().jsonPath("$.detail").value(String.class, d -> assertThat(d).contains("PANTRY"));
	}

	@Test
	void renameToExistingNameIs409() {
		createLocation("Pantry");
		String fridge = createLocation("Fridge");

		put("/api/v1/locations/" + fridge, "{\"name\":\"pantry\"}").expectStatus().isEqualTo(409);
	}

	@Test
	void unknownIdIs404() {
		String missing = "01900000-0000-7000-8000-000000000000";
		put("/api/v1/locations/" + missing, "{\"name\":\"X\"}")
				.expectStatus().isNotFound()
				.expectHeader().contentTypeCompatibleWith(MediaType.APPLICATION_PROBLEM_JSON);
		client.delete().uri("/api/v1/locations/" + missing).exchange().expectStatus().isNotFound();
	}

	@Test
	void malformedIdIs400() {
		client.delete().uri("/api/v1/locations/not-a-uuid").exchange().expectStatus().isBadRequest();
	}

}
